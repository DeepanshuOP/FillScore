"""Generate the open-source package packages/fillscore-metrics from the measurement code of the service (M7).

The package holds the pure measurement formulas (fill metrics, order implementation shortfall, fee rates and the metric registry that
generates the methodology text). Its Python files are copies of ml-service/measure/{registry,metrics,fees,orders}.py with ONE change: the
registry writes the measurement version into the file instead of importing it from the service's config. Because the code is generated,
the published formulas cannot differ from the ones that score accounts; tests/test_metrics_package.py fails when they do.

    python scripts/sync_metrics_package.py           write the files
    python scripts/sync_metrics_package.py --check   exit 1 and name the files that differ (what CI and the test run)
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "ml-service" / "measure"
PKG = ROOT / "packages" / "fillscore-metrics"
IMPORT_LINE = "from config.versions import MEASURE_VERSION\n"
MODULES = ("registry", "metrics", "fees", "orders")

INIT = '''"""fillscore-metrics: the measurement formulas of FillScore, as a small library with no dependencies. See README.md.

Generated by ml-service/scripts/sync_metrics_package.py from the service's own code. Do not edit by hand."""
from .fees import effective_rate
from .metrics import IdentityError, check_decomposition, effective_half_spread_bps, eq_ratio, price_impact_bps, realized_half_spread_bps
from .orders import order_is
from .registry import MEASURE_VERSION, REGISTRY, MetricSpec, methodology_markdown

__all__ = ["effective_rate", "IdentityError", "check_decomposition", "effective_half_spread_bps", "eq_ratio", "price_impact_bps",
           "realized_half_spread_bps", "order_is", "MEASURE_VERSION", "REGISTRY", "MetricSpec", "methodology_markdown"]
__version__ = MEASURE_VERSION
'''

PYPROJECT = '''# Generated by ml-service/scripts/sync_metrics_package.py. The version is the measurement version of FillScore.
[build-system]
requires = ["setuptools>=68"]
build-backend = "setuptools.build_meta"

[project]
name = "fillscore-metrics"
version = "{version}"
description = "Execution-quality metrics of FillScore: effective and realized spread, price impact, implementation shortfall, fee rates. Pure Python, no dependencies."
readme = "README.md"
requires-python = ">=3.10"
license = {{ text = "MIT" }}
dependencies = []

[tool.setuptools]
packages = ["fillscore_metrics"]
'''


def measure_version() -> str:
    for line in (ROOT / "ml-service" / "config" / "versions.py").read_text().splitlines():
        if line.startswith("MEASURE_VERSION"):
            return line.split("=", 1)[1].split("#")[0].strip().strip('"')
    raise RuntimeError("MEASURE_VERSION not found")


def generate() -> dict[Path, str]:
    version = measure_version()
    out: dict[Path, str] = {}
    for name in MODULES:
        text = (SRC / f"{name}.py").read_text()
        if name == "registry":
            if IMPORT_LINE not in text:
                raise RuntimeError("registry.py no longer imports MEASURE_VERSION the expected way")
            text = text.replace(IMPORT_LINE, f'MEASURE_VERSION = "{version}"\n')
        for bad in ("from config", "from measure", "import numpy", "import pandas"):
            if bad in text:
                raise RuntimeError(f"{name}.py imports something the package does not have: {bad}")
        out[PKG / "fillscore_metrics" / f"{name}.py"] = text
    out[PKG / "fillscore_metrics" / "__init__.py"] = INIT
    out[PKG / "pyproject.toml"] = PYPROJECT.format(version=version)
    return out


def check() -> list[str]:
    return [str(p.relative_to(ROOT)) for p, text in generate().items() if not p.exists() or p.read_text() != text]


def write() -> None:
    for p, text in generate().items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)


if __name__ == "__main__":
    if "--check" in sys.argv:
        bad = check()
        print("up to date" if not bad else "differs: " + ", ".join(bad))
        sys.exit(1 if bad else 0)
    write()
    print("written:", ", ".join(str(p.relative_to(ROOT)) for p in generate()))
