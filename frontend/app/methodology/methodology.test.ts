import { describe, it, expect } from 'vitest';
import { readFileSync } from 'fs';
import { join } from 'path';
import { findAdviceTerms, findConnectiveTerms } from '../../../backend/src/constants/adviceTerms';
import data from './methodology.json';

describe('methodology data (generated by ml-service/scripts/gen_methodology.py)', () => {
  it('lists the measured metrics and the scoring version', () => {
    const ids = data.metrics.map(m => m.id);
    for (const id of ['fill.effective_half_spread_bps', 'fill.realized_half_spread_bps', 'fill.price_impact_bps',
      'fill.eq_ratio', 'order.implementation_shortfall_bps', 'fee.effective_rate']) expect(ids).toContain(id);
    expect(data.scoring.version).toMatch(/^v2\.\d+\.\d+$/);
    expect(data.scoring.minFills).toBe(20);
    expect(Object.values(data.scoring.weights).reduce((a, b) => a + b, 0)).toBeCloseTo(1, 12);
  });

  it('has no advice, counterfactual or causal wording in any text shown on the page', () => {
    const text = JSON.stringify(data) + readFileSync(join(process.cwd(), 'app/methodology/page.tsx'), 'utf8');
    expect(findAdviceTerms(text)).toEqual([]);
    expect(findConnectiveTerms(text)).toEqual([]);
  });
});
